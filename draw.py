def text(x, y, s, scale, color):
    cx = x
    for ch in s.upper():
        g = F.get(ch, F[' '])
        for r in range(7):
            bits = g[r]
            for cidx in range(5):
                if bits & (1 << (4 - cidx)):
                    fill(cx + cidx * scale, y + r * scale, cx + (cidx + 1) * scale, y + (r + 1) * scale, color)
        cx += 6 * scale
    return cx
def tw(s, scale): return len(s) * 6 * scale - scale
def center(y, s, scale, color):
    text((W - tw(s, scale)) // 2, y, s, scale, color)

