# Pure-stdlib PNG infographic: world news of Tuesday 17 November 2026.
import zlib, struct

W = H = 1024
px = bytearray(W * H * 3)

def rgb(c): return bytes.fromhex(c)
def fill(x0, y0, x1, y1, c):
    row = rgb(c) * (x1 - x0)
    for y in range(y0, y1):
        i = (y * W + x0) * 3
        px[i:i + len(row)] = row
def rect(x0, y0, x1, y1, c, t=3):
    fill(x0, y0, x1, y0 + t, c); fill(x0, y1 - t, x1, y1, c)
    fill(x0, y0, x0 + t, y1, c); fill(x1 - t, y0, x1, y1, c)

